export function getPhaseByProgress(progress) {
  const p = ((progress % 1) + 1) % 1;
  for (let i = PHASES.length - 1; i >= 0; i--) {
    if (p >= PHASES[i].range[0]) return PHASES[i];
  }
  return PHASES[0];
}
